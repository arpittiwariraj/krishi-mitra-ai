export const getTranslation = (language, path) => {
  const parts = path.split(".");
  let value = translations[language] || translations.en;
  for (const part of parts) {
    if (value && Object.prototype.hasOwnProperty.call(value, part)) {
      value = value[part];
    } else {
      return path;
    }
  }
  return value;
};
